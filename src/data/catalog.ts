export function computeFloorPlanMetrics(fp: FloorPlanData): { roomCount: number; totalAreaSqm: number } {
  const roomCount = fp.rooms.length;
  const totalAreaSqm = Number(
    fp.rooms.reduce((sum, r) => sum + Math.max(0, r.width) * Math.max(0, r.depth), 0).toFixed(1)
  );
  return { roomCount, totalAreaSqm };
}
